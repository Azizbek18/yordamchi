// Language metadata
const langMeta = {
    uz: { label: "O'zbek", flag: "🇺🇿" },
    ru: { label: "Русский", flag: "🇷🇺" },
    en: { label: "English", flag: "🇬🇧" }
};

// ── Core i18n Functions ──

function getCurrentLang() {
    return localStorage.getItem('topshiriq_lang') || 'uz';
}

function setLang(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('topshiriq_lang', lang);
    document.documentElement.lang = lang;
    applyTranslations(lang);
    updateLangSwitcher(lang);
}

function applyTranslations(lang) {
    const t = translations[lang];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            el.textContent = t[key];
        }
    });

    // Also translate elements with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) {
            el.setAttribute('placeholder', t[key]);
        }
    });

    // Also translate elements with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (t[key]) {
            el.setAttribute('title', t[key]);
        }
    });
}

function updateLangSwitcher(lang) {
    const meta = langMeta[lang];
    if (!meta) return;

    // Update the custom select display
    const selectedFlag = document.querySelector('.lang-selected-flag');
    const selectedLabel = document.querySelector('.lang-selected-label');
    
    if (selectedFlag) selectedFlag.textContent = meta.flag;
    if (selectedLabel) selectedLabel.textContent = meta.label;

    // Update active state in dropdown options
    document.querySelectorAll('.lang-option').forEach(opt => {
        opt.classList.toggle('active', opt.dataset.lang === lang);
    });
}

// ── Custom Select Dropdown Logic ──

function initLangSwitcher() {
    const wrapper = document.querySelector('.lang-switcher');
    if (!wrapper) return;

    const trigger = wrapper.querySelector('.lang-trigger');
    const dropdown = wrapper.querySelector('.lang-dropdown');
    const options = wrapper.querySelectorAll('.lang-option');

    // Toggle dropdown
    trigger.addEventListener('click', (e) => {
        e.stopPropagation();
        const isOpen = wrapper.classList.contains('open');
        wrapper.classList.toggle('open');
        trigger.setAttribute('aria-expanded', !isOpen);
    });

    // Select option
    options.forEach(opt => {
        opt.addEventListener('click', (e) => {
            e.stopPropagation();
            const lang = opt.dataset.lang;
            setLang(lang);
            wrapper.classList.remove('open');
            trigger.setAttribute('aria-expanded', 'false');
        });
    });

    // Close on outside click
    document.addEventListener('click', () => {
        wrapper.classList.remove('open');
        trigger.setAttribute('aria-expanded', 'false');
    });

    // Close on Escape
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
            wrapper.classList.remove('open');
            trigger.setAttribute('aria-expanded', 'false');
        }
    });

    // Keyboard navigation
    trigger.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
            e.preventDefault();
            trigger.click();
        }
    });

    // Apply saved language on load
    const savedLang = getCurrentLang();
    setLang(savedLang);
}

// ── Initialize on DOM ready ──
document.addEventListener('DOMContentLoaded', initLangSwitcher);
